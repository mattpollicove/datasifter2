"""Build date and time shown in the window title for testing."""

from __future__ import annotations

import sys
from datetime import UTC, datetime
from pathlib import Path

STAMP_MODULE = "_build_stamp.py"


def write_build_stamp(package_dir: Path, moment: datetime | None = None) -> str:
    """Record the build time (UTC, ISO 8601) in a generated module bundled with the build."""
    stamp = (moment or datetime.now(UTC)).astimezone(UTC).isoformat(timespec="seconds")
    target = package_dir / STAMP_MODULE
    temporary = target.with_suffix(".tmp")
    try:
        temporary.write_text(
            f'"""Generated by the standalone build; do not edit."""\n\nBUILD_TIMESTAMP = "{stamp}"\n',
            encoding="utf-8",
        )
        temporary.replace(target)
    finally:
        temporary.unlink(missing_ok=True)
    return stamp


def _stamped_time() -> datetime | None:
    try:
        from datasifter._build_stamp import BUILD_TIMESTAMP
    except ImportError:
        return None
    try:
        return datetime.fromisoformat(BUILD_TIMESTAMP)
    except (TypeError, ValueError):
        return None


def _source_time() -> datetime | None:
    package_dir = Path(__file__).resolve().parent
    times = [path.stat().st_mtime for path in package_dir.rglob("*.py")]
    return datetime.fromtimestamp(max(times), UTC) if times else None


def build_time() -> tuple[datetime | None, bool]:
    """Return (time, is_standalone_build); source runs use the newest source file time."""
    if getattr(sys, "frozen", False):
        return _stamped_time(), True
    return _source_time(), False


def build_label() -> str:
    moment, frozen = build_time()
    if moment is None:
        return "build time unknown"
    local = moment.astimezone().strftime("%Y-%m-%d %H:%M:%S")
    return f"built {local}" if frozen else f"source {local}"
